-- V6: Subscription, Payment and Advertisement

-- 1. Subscriptions
CREATE TABLE subscriptions (
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL
        REFERENCES business_profiles(business_id),
    start_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    monthly_fee NUMERIC(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_subscription_dates
        CHECK (end_date > start_date),

    CONSTRAINT chk_subscription_fee
        CHECK (monthly_fee >= 0),

    CONSTRAINT chk_subscription_status
        CHECK (status IN (
            'PENDING', 'ACTIVE', 'EXPIRED', 'CANCELLED'
        ))
);

-- Only one active subscription per business
CREATE UNIQUE INDEX uq_business_active_subscription
ON subscriptions(business_id)
WHERE status = 'ACTIVE';


-- 2. Payments
CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL
        REFERENCES subscriptions(subscription_id),
    user_id BIGINT NOT NULL
        REFERENCES users(user_id),
    amount NUMERIC(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    payment_method VARCHAR(50),
    payment_gateway VARCHAR(50),
    transaction_reference VARCHAR(255),
    payment_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_payment_amount
        CHECK (amount > 0),

    CONSTRAINT chk_payment_type
        CHECK (payment_type IN (
            'INITIAL', 'RENEWAL'
        )),

    CONSTRAINT chk_payment_status
        CHECK (status IN (
            'PENDING', 'SUCCESS', 'FAILED',
            'CANCELLED', 'REFUNDED'
        )),

    CONSTRAINT uq_payment_transaction
        UNIQUE (payment_gateway, transaction_reference)
);


-- 3. Advertisements
CREATE TABLE advertisements (
    advertisement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL
        REFERENCES business_profiles(business_id),
    listing_id BIGINT NOT NULL
        REFERENCES business_listings(listing_id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    image_url TEXT,
    target_url TEXT,
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_advertisement_dates
        CHECK (
            start_at IS NULL
            OR end_at IS NULL
            OR end_at > start_at
        ),

    CONSTRAINT chk_advertisement_status
        CHECK (status IN (
            'DRAFT', 'PENDING', 'APPROVED',
            'REJECTED', 'PUBLISHED',
            'EXPIRED', 'SUSPENDED'
        ))
);


-- Indexes
CREATE INDEX idx_payments_subscription
ON payments(subscription_id);

CREATE INDEX idx_advertisements_listing
ON advertisements(listing_id);