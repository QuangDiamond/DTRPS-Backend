
-- V6: Subscription, Payment and Advertisement

-- 1. Subscriptions
CREATE TABLE subscriptions (
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL
        REFERENCES business_profiles(business_id),
    start_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    monthly_fee NUMERIC(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_subscription_dates
        CHECK (end_date > start_date),

    CONSTRAINT chk_subscription_fee
        CHECK (monthly_fee >= 0),

    CONSTRAINT chk_subscription_status
        CHECK (status IN (
            'PENDING', 'ACTIVE', 'EXPIRED', 'CANCELLED'
        ))
);

-- Only one active subscription per business
CREATE UNIQUE INDEX uq_business_active_subscription
ON subscriptions(business_id)
WHERE status = 'ACTIVE';

-- 2. Subscription Renewal Windows
CREATE TABLE subscription_renewal_windows (
    renewal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL
        REFERENCES subscriptions(subscription_id),
    notification_id BIGINT
        REFERENCES notifications(notification_id),
    opens_at TIMESTAMPTZ NOT NULL,
    closes_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_renewal_window_dates
        CHECK (closes_at > opens_at),

    CONSTRAINT chk_renewal_window_status
        CHECK (status IN (
            'PENDING', 'OPEN', 'USED', 'EXPIRED', 'CANCELLED'
        ))
);

CREATE UNIQUE INDEX uq_open_renewal_window
ON subscription_renewal_windows(subscription_id)
WHERE status = 'OPEN';

-- 3. Payments
CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL
        REFERENCES subscriptions(subscription_id),
    renewal_id BIGINT
        REFERENCES subscription_renewal_windows(renewal_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    amount NUMERIC(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    payment_method VARCHAR(50),
    payment_gateway VARCHAR(50),
    transaction_reference VARCHAR(255),
    payment_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_payment_amount
        CHECK (amount > 0),

    CONSTRAINT chk_payment_type
        CHECK (payment_type IN (
            'INITIAL', 'RENEWAL'
        )),

    CONSTRAINT chk_payment_status
        CHECK (status IN (
            'PENDING', 'SUCCESS', 'FAILED', 'CANCELLED',
            'REFUNDED'
        )),

    CONSTRAINT chk_renewal_payment_reference
        CHECK (
            payment_type <> 'RENEWAL'
            OR renewal_id IS NOT NULL
        ),

    CONSTRAINT uq_payment_transaction
        UNIQUE (payment_gateway, transaction_reference)
);

-- 4. Advertisements
CREATE TABLE advertisements (
    advertisement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL
        REFERENCES business_profiles(business_id),
    listing_id BIGINT NOT NULL
        REFERENCES business_listings(listing_id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    image_url TEXT,
    target_url TEXT,
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_advertisement_dates
        CHECK (
            start_at IS NULL
            OR end_at IS NULL
            OR end_at > start_at
        ),

    CONSTRAINT chk_advertisement_status
        CHECK (status IN (
            'DRAFT', 'PENDING', 'APPROVED',
            'REJECTED', 'PUBLISHED', 'EXPIRED',
            'SUSPENDED'
        ))
);

-- 5. Advertisement Reviews
CREATE TABLE advertisement_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertisement_id BIGINT NOT NULL
        REFERENCES advertisements(advertisement_id),
    reviewed_by BIGINT NOT NULL REFERENCES users(user_id),
    decision VARCHAR(30) NOT NULL,
    review_note TEXT,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_advertisement_review_decision
        CHECK (decision IN ('APPROVED', 'REJECTED'))
);

-- Indexes
CREATE INDEX idx_subscriptions_business
    ON subscriptions(business_id);

CREATE INDEX idx_subscriptions_end_date
    ON subscriptions(end_date);

CREATE INDEX idx_renewal_subscription
    ON subscription_renewal_windows(subscription_id);

CREATE INDEX idx_renewal_notification
    ON subscription_renewal_windows(notification_id);

CREATE INDEX idx_payments_subscription
    ON payments(subscription_id);

CREATE INDEX idx_payments_renewal
    ON payments(renewal_id);

CREATE INDEX idx_payments_user
    ON payments(user_id);

CREATE INDEX idx_payments_status
    ON payments(status);

CREATE INDEX idx_advertisements_business
    ON advertisements(business_id);

CREATE INDEX idx_advertisements_listing
    ON advertisements(listing_id);

CREATE INDEX idx_advertisements_status
    ON advertisements(status);

CREATE INDEX idx_advertisement_reviews_ad
    ON advertisement_reviews(advertisement_id);
