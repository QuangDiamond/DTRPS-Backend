
-- V3: Travel Planning Module

-- 1. Travel Plans
CREATE TABLE travel_plans (
    plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    title VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    budget NUMERIC(15,2),
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    group_size INTEGER NOT NULL DEFAULT 1,
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_plan_dates
        CHECK (end_date >= start_date),

    CONSTRAINT chk_plan_budget
        CHECK (budget IS NULL OR budget >= 0),

    CONSTRAINT chk_plan_group_size
        CHECK (group_size > 0)
);

-- 2. Plan Places
-- Candidate places associated with a travel plan
CREATE TABLE plan_places (
    plan_place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES travel_plans(plan_id),
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    source VARCHAR(30) NOT NULL DEFAULT 'USER',
    priority INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_plan_place UNIQUE (plan_id, place_id)
);

-- 3. Plan Interests
CREATE TABLE plan_interests (
    interest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES travel_plans(plan_id),
    interest_name VARCHAR(100) NOT NULL,

    CONSTRAINT uq_plan_interest
        UNIQUE (plan_id, interest_name)
);

-- 4. Trip Feedback
CREATE TABLE trip_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES travel_plans(plan_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    rating SMALLINT NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_trip_feedback_rating
        CHECK (rating BETWEEN 1 AND 5),

    CONSTRAINT uq_trip_feedback_user_plan
        UNIQUE (plan_id, user_id)
);

-- Indexes

CREATE INDEX idx_travel_plans_user_created
ON travel_plans(user_id, created_at DESC);
