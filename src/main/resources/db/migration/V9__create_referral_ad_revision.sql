
-- V9: Referral and Advertisement Revision

-- 1. Referrals
CREATE TABLE referrals (
    referral_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id),
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    business_id BIGINT REFERENCES business_profiles(business_id),
    referral_source VARCHAR(50) NOT NULL DEFAULT 'DISCOVERY',
    destination_url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_referral_source
        CHECK (referral_source IN (
            'DISCOVERY', 'ITINERARY', 'ADVERTISEMENT'
        ))
);

-- 2. Advertisement Revisions
CREATE TABLE advertisement_revisions (
    revision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertisement_id BIGINT NOT NULL
        REFERENCES advertisements(advertisement_id),
    revision_number INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    image_url TEXT,
    target_url TEXT,
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    submitted_at TIMESTAMPTZ,
    reviewed_by BIGINT REFERENCES users(user_id),
    reviewed_at TIMESTAMPTZ,
    rejection_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_ad_revision_number
        CHECK (revision_number > 0),

    CONSTRAINT chk_ad_revision_status
        CHECK (status IN (
            'DRAFT', 'PENDING', 'APPROVED',
            'REJECTED', 'CANCELLED'
        )),

    CONSTRAINT chk_ad_revision_dates
        CHECK (
            start_at IS NULL
            OR end_at IS NULL
            OR end_at > start_at
        ),

    CONSTRAINT uq_ad_revision_number
        UNIQUE (advertisement_id, revision_number)
);

-- One pending revision per advertisement
CREATE UNIQUE INDEX uq_ad_pending_revision
ON advertisement_revisions(advertisement_id)
WHERE status = 'PENDING';

-- Indexes
CREATE INDEX idx_referrals_user
    ON referrals(user_id);

CREATE INDEX idx_referrals_place
    ON referrals(place_id);

CREATE INDEX idx_referrals_business
    ON referrals(business_id);

CREATE INDEX idx_ad_revisions_advertisement
    ON advertisement_revisions(advertisement_id);

CREATE INDEX idx_ad_revisions_status
    ON advertisement_revisions(status);
