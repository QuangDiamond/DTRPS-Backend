
-- V8: Trip Tracking and Weather

-- 1. Trip Progress
CREATE TABLE trip_progress (
    progress_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    itinerary_id BIGINT NOT NULL UNIQUE
        REFERENCES itineraries(itinerary_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    status VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED',
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_trip_progress_status
        CHECK (status IN (
            'NOT_STARTED', 'IN_PROGRESS',
            'COMPLETED', 'CANCELLED'
        ))
);

-- 2. Activity Progress
CREATE TABLE activity_progress (
    activity_progress_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    progress_id BIGINT NOT NULL
        REFERENCES trip_progress(progress_id),
    item_id BIGINT NOT NULL
        REFERENCES itinerary_items(item_id),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    completed_at TIMESTAMPTZ,
    notes TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_activity_progress_item
        UNIQUE (progress_id, item_id),

    CONSTRAINT chk_activity_progress_status
        CHECK (status IN (
            'PENDING', 'COMPLETED', 'SKIPPED'
        ))
);

-- 3. Weather Forecasts
CREATE TABLE weather_forecasts (
    forecast_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    forecast_date DATE NOT NULL,
    temperature_min NUMERIC(5,2),
    temperature_max NUMERIC(5,2),
    weather_condition VARCHAR(100),
    precipitation_probability NUMERIC(5,2),
    source VARCHAR(100),
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_weather_temperature
        CHECK (
            temperature_min IS NULL
            OR temperature_max IS NULL
            OR temperature_min <= temperature_max
        ),

    CONSTRAINT chk_precipitation_probability
        CHECK (
            precipitation_probability IS NULL
            OR precipitation_probability BETWEEN 0 AND 100
        ),

    CONSTRAINT uq_weather_place_date
        UNIQUE (place_id, forecast_date)
);

-- Indexes
CREATE INDEX idx_trip_progress_user
    ON trip_progress(user_id);

CREATE INDEX idx_activity_progress_item
    ON activity_progress(item_id);

CREATE INDEX idx_weather_forecasts_date
    ON weather_forecasts(forecast_date);
