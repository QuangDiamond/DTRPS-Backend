
-- V2: Discovery Module

-- 1. Place Categories
CREATE TABLE place_categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
);

-- 2. Places
CREATE TABLE places (
    place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES place_categories(category_id),
    name VARCHAR(255) NOT NULL,
    description TEXT,
    address TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    city VARCHAR(100),
    province VARCHAR(100),
    external_place_id VARCHAR(255),
    place_type VARCHAR(50),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_place_latitude
        CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_place_longitude
        CHECK (longitude BETWEEN -180 AND 180)
);

-- 3. Place Images
CREATE TABLE place_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    image_url TEXT NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Place Opening Hours
CREATE TABLE place_opening_hours (
    opening_hour_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    day_of_week SMALLINT NOT NULL,
    open_time TIME,
    close_time TIME,
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_day_of_week
        CHECK (day_of_week BETWEEN 1 AND 7),

    CONSTRAINT uq_place_opening_day
        UNIQUE (place_id, day_of_week)
);

-- 5. Place Prices
CREATE TABLE place_prices (
    price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    price_type VARCHAR(100) NOT NULL,
    amount NUMERIC(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    description TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_place_price_amount
        CHECK (amount >= 0)
);

-- 6. Place Reviews
CREATE TABLE place_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    rating SMALLINT NOT NULL,
    comment TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'VISIBLE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_place_rating
        CHECK (rating BETWEEN 1 AND 5)
);

-- 7. Favorites
CREATE TABLE favorites (
    favorite_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_user_favorite_place
        UNIQUE (user_id, place_id)
);

-- 8. Route Information
CREATE TABLE route_info (
    route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_place_id BIGINT NOT NULL REFERENCES places(place_id),
    to_place_id BIGINT NOT NULL REFERENCES places(place_id),
    distance_meters DOUBLE PRECISION,
    travel_time_minutes INTEGER,
    transport_mode VARCHAR(50),
    route_data JSONB,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_route_distance
        CHECK (distance_meters >= 0),
    CONSTRAINT chk_route_travel_time
        CHECK (travel_time_minutes >= 0),
    CONSTRAINT chk_route_different_places
        CHECK (from_place_id <> to_place_id)
);

-- Indexes
CREATE INDEX idx_places_category ON places(category_id);
CREATE INDEX idx_places_city ON places(city);
CREATE INDEX idx_places_province ON places(province);
CREATE INDEX idx_place_images_place ON place_images(place_id);
CREATE INDEX idx_place_prices_place ON place_prices(place_id);
CREATE INDEX idx_place_reviews_place ON place_reviews(place_id);
CREATE INDEX idx_place_reviews_user ON place_reviews(user_id);
CREATE INDEX idx_favorites_place ON favorites(place_id);
CREATE INDEX idx_route_from_place ON route_info(from_place_id);
CREATE INDEX idx_route_to_place ON route_info(to_place_id);

-- Only one primary image per place
CREATE UNIQUE INDEX uq_place_primary_image
ON place_images(place_id)
WHERE is_primary = TRUE;
