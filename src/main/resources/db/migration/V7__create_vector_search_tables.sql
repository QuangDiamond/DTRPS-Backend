
-- V7: Vector Search Module
-- AI generates embeddings.
-- System performs recommendation and scheduling.

-- 1. Enable pgvector
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Embedding Models
CREATE TABLE embedding_models (
    model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(150) NOT NULL,
    model_version VARCHAR(100) NOT NULL,
    vector_dimensions INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_embedding_dimensions
        CHECK (vector_dimensions BETWEEN 1 AND 16000),

    CONSTRAINT uq_embedding_model
        UNIQUE (model_name, model_version)
);

-- 3. Place Embeddings
CREATE TABLE place_embeddings (
    embedding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES places(place_id),
    model_id BIGINT NOT NULL REFERENCES embedding_models(model_id),

    -- Flexible dimensions until the embedding model is finalized
    embedding VECTOR NOT NULL,

    source_text TEXT NOT NULL,
    source_hash VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_place_embedding_model
        UNIQUE (place_id, model_id)
);

-- 4. Search Logs
CREATE TABLE search_logs (
    search_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id),
    model_id BIGINT REFERENCES embedding_models(model_id),
    search_query TEXT NOT NULL,
    filters JSONB,
    result_count INTEGER,
    processing_time_ms INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_search_result_count
        CHECK (result_count IS NULL OR result_count >= 0),

    CONSTRAINT chk_search_processing_time
        CHECK (
            processing_time_ms IS NULL
            OR processing_time_ms >= 0
        )
);

-- Indexes
CREATE INDEX idx_place_embeddings_place
    ON place_embeddings(place_id);

CREATE INDEX idx_place_embeddings_model
    ON place_embeddings(model_id);

CREATE INDEX idx_search_logs_user
    ON search_logs(user_id);

CREATE INDEX idx_search_logs_created_at
    ON search_logs(created_at);
