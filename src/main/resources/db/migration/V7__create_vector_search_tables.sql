-- V7: Vector Search Module
-- AI generates embeddings.
-- System performs recommendation and scheduling.

-- 1. Enable pgvector
CREATE EXTENSION IF NOT EXISTS vector;


-- 2. Place Embeddings
CREATE TABLE place_embeddings (
    embedding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL UNIQUE
        REFERENCES places(place_id),

    -- Example: embedding model outputs 1536 dimensions
    embedding VECTOR(1536) NOT NULL,

    source_text TEXT NOT NULL,
    source_hash VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- 3. Search Logs
CREATE TABLE search_logs (
    search_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id),
    search_query TEXT NOT NULL,
    filters JSONB,
    result_count INTEGER,
    processing_time_ms INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_search_result_count
        CHECK (
            result_count IS NULL
            OR result_count >= 0
        ),

    CONSTRAINT chk_search_processing_time
        CHECK (
            processing_time_ms IS NULL
            OR processing_time_ms >= 0
        )
);


-- 4. Vector Index
CREATE INDEX idx_place_embeddings_vector
ON place_embeddings
USING hnsw (embedding vector_cosine_ops);