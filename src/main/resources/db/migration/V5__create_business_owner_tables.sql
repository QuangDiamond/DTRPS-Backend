
-- V5: Business Owner Management

-- 1. Business Profiles
CREATE TABLE business_profiles (
    business_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id),
    business_name VARCHAR(255) NOT NULL,
    contact_email VARCHAR(255),
    contact_phone VARCHAR(20),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    approved_by BIGINT REFERENCES users(user_id),
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_business_profile_status
        CHECK (status IN (
            'PENDING', 'ACTIVE', 'SUSPENDED', 'INACTIVE'
        ))
);

-- 2. Owner Applications
CREATE TABLE owner_applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    business_name VARCHAR(255) NOT NULL,
    place_id BIGINT REFERENCES places(place_id),
    contact_email VARCHAR(255),
    contact_phone VARCHAR(20),
    business_documents JSONB,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    reviewed_by BIGINT REFERENCES users(user_id),
    reviewed_at TIMESTAMPTZ,
    rejection_reason TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_owner_application_status
        CHECK (status IN (
            'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'
        ))
);

-- Only one pending application per user
CREATE UNIQUE INDEX uq_owner_pending_application
ON owner_applications(user_id)
WHERE status = 'PENDING';

-- 3. Business Listings
CREATE TABLE business_listings (
    listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL UNIQUE
        REFERENCES business_profiles(business_id),
    place_id BIGINT NOT NULL UNIQUE
        REFERENCES places(place_id),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    approved_by BIGINT REFERENCES users(user_id),
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_business_listing_status
        CHECK (status IN (
            'PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED'
        ))
);

-- 4. Business Listing Changes
CREATE TABLE business_listing_changes (
    change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL
        REFERENCES business_listings(listing_id),
    requested_by BIGINT NOT NULL REFERENCES users(user_id),
    proposed_data JSONB NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    reviewed_by BIGINT REFERENCES users(user_id),
    reviewed_at TIMESTAMPTZ,
    rejection_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_business_change_status
        CHECK (status IN (
            'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'
        )),

    CONSTRAINT chk_business_change_data
        CHECK (jsonb_typeof(proposed_data) = 'object')
);

-- One pending change request per listing
CREATE UNIQUE INDEX uq_listing_pending_change
ON business_listing_changes(listing_id)
WHERE status = 'PENDING';

-- Indexes
CREATE INDEX idx_owner_applications_user
    ON owner_applications(user_id);

CREATE INDEX idx_owner_applications_place
    ON owner_applications(place_id);

CREATE INDEX idx_business_listings_place
    ON business_listings(place_id);

CREATE INDEX idx_business_changes_listing
    ON business_listing_changes(listing_id);

CREATE INDEX idx_business_changes_requested_by
    ON business_listing_changes(requested_by);
