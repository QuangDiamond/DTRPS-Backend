
-- V4: Itinerary Management Module

-- 1. Itineraries
CREATE TABLE itineraries (
    itinerary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES travel_plans(plan_id),
    title VARCHAR(255) NOT NULL,
    version_number INTEGER NOT NULL DEFAULT 1,
   generation_source VARCHAR(30) NOT NULL DEFAULT 'SYSTEM',
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    total_estimated_cost NUMERIC(15,2),
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_itinerary_version
        CHECK (version_number > 0),

    CONSTRAINT chk_itinerary_cost
        CHECK (
            total_estimated_cost IS NULL
            OR total_estimated_cost >= 0
        ),

    CONSTRAINT uq_itinerary_plan_version
        UNIQUE (plan_id, version_number)
);

-- 2. Itinerary Days
CREATE TABLE itinerary_days (
    day_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    itinerary_id BIGINT NOT NULL
        REFERENCES itineraries(itinerary_id),
    day_number INTEGER NOT NULL,
    visit_date DATE NOT NULL,
    title VARCHAR(255),
    notes TEXT,
    estimated_cost NUMERIC(15,2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_itinerary_day_number
        CHECK (day_number > 0),

    CONSTRAINT chk_itinerary_day_cost
        CHECK (
            estimated_cost IS NULL
            OR estimated_cost >= 0
        ),

    CONSTRAINT uq_itinerary_day_number
        UNIQUE (itinerary_id, day_number),

    CONSTRAINT uq_itinerary_visit_date
        UNIQUE (itinerary_id, visit_date)
);

-- 3. Itinerary Items
CREATE TABLE itinerary_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_id BIGINT NOT NULL
        REFERENCES itinerary_days(day_id),
    place_id BIGINT NOT NULL
        REFERENCES places(place_id),
    item_order INTEGER NOT NULL,
    start_time TIME,
    end_time TIME,
    estimated_cost NUMERIC(15,2),
    transport_mode VARCHAR(50),
    travel_time_minutes INTEGER,
    notes TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PLANNED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_itinerary_item_order
        CHECK (item_order > 0),

    CONSTRAINT chk_itinerary_item_time
        CHECK (
            start_time IS NULL
            OR end_time IS NULL
            OR end_time > start_time
        ),

    CONSTRAINT chk_itinerary_item_cost
        CHECK (
            estimated_cost IS NULL
            OR estimated_cost >= 0
        ),

    CONSTRAINT chk_itinerary_travel_time
        CHECK (
            travel_time_minutes IS NULL
            OR travel_time_minutes >= 0
        ),

    CONSTRAINT uq_itinerary_day_order
        UNIQUE (day_id, item_order)
);

-- 4. Itinerary Shares
CREATE TABLE itinerary_shares (
    share_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    itinerary_id BIGINT NOT NULL
        REFERENCES itineraries(itinerary_id),
    created_by BIGINT NOT NULL
        REFERENCES users(user_id),
    share_token UUID NOT NULL UNIQUE,
    access_type VARCHAR(30) NOT NULL DEFAULT 'VIEW',
    expires_at TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_itinerary_share_access
        CHECK (access_type IN ('VIEW', 'EDIT'))
);

-- Indexes
CREATE INDEX idx_itineraries_plan
    ON itineraries(plan_id);

CREATE INDEX idx_itinerary_days_itinerary
    ON itinerary_days(itinerary_id);

CREATE INDEX idx_itinerary_items_day
    ON itinerary_items(day_id);

CREATE INDEX idx_itinerary_items_place
    ON itinerary_items(place_id);

CREATE INDEX idx_itinerary_shares_itinerary
    ON itinerary_shares(itinerary_id);

CREATE INDEX idx_itinerary_shares_creator
    ON itinerary_shares(created_by);
